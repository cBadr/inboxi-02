export function SocialLinks({
  socials,
  className = '',
}: {
  socials: Social[];
  className?: string;
}) {
  const active = socials.filter((s) => s.url && s.url.trim() && s.url !== '#');
  if (active.length === 0) return null;
  return (
    <div className={`flex items-center gap-2 ${className}`}>
      {active.map((s) => (
        <a
          key={s.platform}
          href={s.url}
          target="_blank"
          rel="noreferrer"
          aria-label={s.platform}
          title={s.platform}
          className="flex h-9 w-9 items-center justify-center rounded-full border border-gray-200 bg-white text-gray-500 transition hover:-translate-y-0.5 hover:border-brand/40 hover:text-brand hover:shadow-sm"
        >
          <Glyph platform={s.platform} />
        </a>
      ))}
    </div>
  );
}
